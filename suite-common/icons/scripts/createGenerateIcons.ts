import path from 'path';
import { format, resolveConfig } from 'prettier';
import { type Config, optimize } from 'svgo';

import type { LoggerDep } from '@trezor/logger';
import type { ReadDirectoryDep, ReadFileDep, WriteFileDep } from '@trezor/type-utils';

type IconAssetModule = {
    name: string;
    packageName: string;
};

type IconAssetType = {
    name: string;
    directory: string;
    typeName: string;
    isRaster?: boolean;
    module?: IconAssetModule;
};

type IconAssetGroup = {
    label: string;
    assetTypes: readonly IconAssetType[];
    outputFilePath?: string;
};

type IconAsset = {
    fileName: string;
    content?: string;
};

type OptimizedIconAssetType = IconAssetType & { assets: IconAsset[] };

type IconEntry = { symbol: string; source: string };

type IconRegistry = { typeName: string; entries: IconEntry[] };

export type GenerateIconsDeps = LoggerDep &
    ReadDirectoryDep &
    ReadFileDep &
    WriteFileDep & {
        repositoryRoot: string;
    };

export type GenerateIcons = () => Promise<void>;

export type GenerateIconsDep = { generateIcons: GenerateIcons };

const generatedFileHeader =
    '// !!! IMPORTANT: This file is autogenerated !!! [by suite-common/icons/scripts/createGenerateIcons.ts]';

const getAssetSymbol = (fileName: string): string => fileName.replace(/\.(svg|webp)$/, '');

const getRelativeAssetPath = (outputFilePath: string, assetPath: string): string => {
    const relativePath = path
        .relative(path.dirname(outputFilePath), assetPath)
        .split(path.sep)
        .join('/');

    return relativePath.startsWith('.') ? relativePath : `./${relativePath}`;
};

type GenerateIconsFileContentParams = {
    assetTypes: OptimizedIconAssetType[];
    outputFilePath: string;
};

const generateIconsFileContent = ({
    assetTypes,
    outputFilePath,
}: GenerateIconsFileContentParams): string => {
    const imports = new Set<string>();
    const assetGroups = new Map<string, IconRegistry>();

    assetTypes.forEach(({ name, assets, directory, typeName, module }) => {
        if (module) {
            imports.add(`import { ${module.name} } from '${module.packageName}';`);
        }

        const group: IconRegistry = assetGroups.get(name) ?? { typeName, entries: [] };
        assets.forEach(({ fileName }) => {
            const symbol = getAssetSymbol(fileName);
            const assetPath = getRelativeAssetPath(outputFilePath, path.join(directory, fileName));
            const source = module
                ? `${module.name}.getIcons('${symbol}').${name === 'cryptoIcons' ? 'coin' : 'network'}`
                : `require('${assetPath}')`;
            group.entries.push({ symbol, source });
        });
        assetGroups.set(name, group);
    });

    const mappedAssetTypes = [...assetGroups].map(
        ([name, { typeName, entries }]) => `
            export const ${name} = {
                ${entries
                    .toSorted((first, second) => first.symbol.localeCompare(second.symbol))
                    .map(({ symbol, source }) => `${symbol}: ${source}`)
                    .join(',')}
            } as const;
            export type ${typeName} = keyof typeof ${name};
        `,
    );

    return `
        ${generatedFileHeader}
        // To add or modify icons, follow suite-common/icons/README.md.

        ${[...imports].join('\n')}
        ${mappedAssetTypes.join('')}
    `;
};

const svgoConfig: Config = {
    multipass: true,
    js2svg: { indent: 2, pretty: true },
    plugins: [
        { name: 'preset-default' },
        {
            name: 'addAttributesToSVGElement',
            params: { attributes: [{ xmlns: 'http://www.w3.org/2000/svg' }] },
        },
        'prefixIds',
        // Removing dimensions allows consumers to resize icons; viewBox stays intact.
        'removeDimensions',
        'removeRasterImages',
        'removeScripts',
        'convertStyleToAttrs',
    ],
};

export const createGenerateIcons = (deps: GenerateIconsDeps): GenerateIcons => {
    const iconsDirectory = path.join(deps.repositoryRoot, 'suite-common/icons');
    const networkAssetPackages = [
        'bitcoin',
        'cardano',
        'ethereum',
        'monero',
        'ripple',
        'solana',
        'stellar',
        'tezos',
        'tron',
    ];
    const createNetworkAssetTypes = (
        name: 'cryptoIcons' | 'networkIcons',
        typeName: 'CryptoIconName' | 'NetworkIconName',
    ): IconAssetType[] =>
        networkAssetPackages.map(family => ({
            name,
            typeName,
            directory: path.join(
                deps.repositoryRoot,
                `networks/${family}/network-${family}-assets/assets/${name}`,
            ),
            module: {
                name: `${family}Assets`,
                packageName: `@trezor/network-${family}-assets`,
            },
        }));
    const assetGroups: IconAssetGroup[] = [
        {
            label: 'icons',
            assetTypes: [
                {
                    name: 'icons',
                    typeName: 'IconName',
                    directory: path.join(deps.repositoryRoot, 'packages/icons/assets'),
                },
            ],
            outputFilePath: path.join(iconsDirectory, 'src/icons.ts'),
        },
        {
            label: 'crypto icons',
            assetTypes: [
                {
                    name: 'cryptoIcons',
                    typeName: 'CryptoIconName',
                    directory: path.join(iconsDirectory, 'cryptoAssets/cryptoIcons'),
                },
                ...createNetworkAssetTypes('cryptoIcons', 'CryptoIconName'),
            ],
            outputFilePath: path.join(iconsDirectory, 'src/cryptoIcons.ts'),
        },
        {
            label: 'network icons',
            assetTypes: createNetworkAssetTypes('networkIcons', 'NetworkIconName'),
            outputFilePath: path.join(iconsDirectory, 'src/networkIcons.ts'),
        },
        {
            label: 'payment method logos',
            assetTypes: [
                {
                    name: 'paymentMethodLogos',
                    typeName: 'PaymentMethodLogoName',
                    directory: path.join(iconsDirectory, 'paymentMethods'),
                    isRaster: true,
                },
            ],
            outputFilePath: path.join(iconsDirectory, 'src/paymentMethodLogos.ts'),
        },
    ];

    const getOptimizedAssetType = async (
        config: IconAssetType,
    ): Promise<OptimizedIconAssetType> => {
        const fileNames = await deps.readDirectory(config.directory);
        const assets: IconAsset[] = [];
        const extension = config.isRaster ? '.webp' : '.svg';

        for (const fileName of fileNames.filter(name => name.endsWith(extension)).toSorted()) {
            if (config.isRaster) {
                assets.push({ fileName });
            } else {
                const content = await deps.readFile(path.join(config.directory, fileName));
                assets.push({
                    fileName,
                    content: optimize(content.toString(), svgoConfig).data,
                });
            }
        }

        return { ...config, assets };
    };

    const writeTypescript = async (filePath: string, source: string): Promise<void> => {
        const prettierConfig = await resolveConfig(path.join(iconsDirectory, 'src/icons.ts'));
        const formattedSource = await format(source, {
            ...prettierConfig,
            parser: 'babel-ts',
        });
        await deps.writeFile(filePath, Buffer.from(formattedSource));
    };

    return async () => {
        for (const group of assetGroups) {
            deps.logger.log(`Generating ${group.label} TS files...`);
            const assetTypes: OptimizedIconAssetType[] = [];

            for (const config of group.assetTypes) {
                assetTypes.push(await getOptimizedAssetType(config));
            }

            if (group.outputFilePath) {
                await writeTypescript(
                    group.outputFilePath,
                    generateIconsFileContent({ assetTypes, outputFilePath: group.outputFilePath }),
                );
            }

            for (const assetType of assetTypes) {
                for (const { fileName, content } of assetType.assets) {
                    if (content !== undefined) {
                        await deps.writeFile(
                            path.join(assetType.directory, fileName),
                            Buffer.from(content),
                        );
                    }
                }
            }

            deps.logger.log(`${group.label} TS files generated successfully`);
        }
    };
};
