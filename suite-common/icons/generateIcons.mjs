import chalk from 'chalk';
import fs from 'fs';
import path from 'path';
import prettier from 'prettier';
import { optimize } from 'svgo';
import { fileURLToPath } from 'url';

const __dirname = path.dirname(fileURLToPath(import.meta.url));
const generatorPath = path
    .relative(path.resolve(__dirname, '../..'), fileURLToPath(import.meta.url))
    .split(path.sep)
    .join('/');
const generatedFileHeader = `// !!! IMPORTANT: This file is autogenerated !!! [by ${generatorPath}]`;

const iconsFilePath = './src/icons.ts';
const cryptoIconsPath = './src/cryptoIcons.ts';
const networkIconsPath = './src/networkIcons.ts';
const paymentMethodLogosPath = './src/paymentMethodLogos.ts';

const assetTypesConfig = [
    {
        name: 'icons',
        dirname: '../../packages/icons/assets',
        typeName: 'IconName',
    },
];

const networkAssetModules = [
    { family: 'bitcoin', dirname: '../../networks/bitcoin/network-bitcoin-assets' },
    { family: 'cardano', dirname: '../../networks/cardano/network-cardano-assets' },
    { family: 'ethereum', dirname: '../../networks/ethereum/network-ethereum-assets' },
    { family: 'monero', dirname: '../../networks/monero/network-monero-assets' },
    { family: 'ripple', dirname: '../../networks/ripple/network-ripple-assets' },
    { family: 'solana', dirname: '../../networks/solana/network-solana-assets' },
    { family: 'stellar', dirname: '../../networks/stellar/network-stellar-assets' },
    { family: 'tezos', dirname: '../../networks/tezos/network-tezos-assets' },
    { family: 'tron', dirname: '../../networks/tron/network-tron-assets' },
];

const cryptoAssetsTypesConfig = [
    {
        name: 'cryptoIcons',
        dirname: 'cryptoAssets/cryptoIcons',
        typeName: 'CryptoIconName',
    },
    ...networkAssetModules.map(({ family, dirname }) => ({
        name: 'cryptoIcons',
        dirname: `${dirname}/assets/cryptoIcons`,
        typeName: 'CryptoIconName',
        family,
    })),
];

const paymentMethodLogosAssetsTypesConfig = [
    {
        name: 'paymentMethodLogos',
        dirname: 'paymentMethods',
        typeName: 'PaymentMethodLogoName',
        raster: true,
    },
];

const networkAssetsTypesConfig = networkAssetModules.map(({ family, dirname }) => ({
    name: 'networkIcons',
    dirname: `${dirname}/assets/networkIcons`,
    typeName: 'NetworkIconName',
    family,
}));

// https://github.com/svg/svgo#built-in-plugins
/**
 * @type {import('svgo').Config}
 */
const svgoConfig = {
    multipass: true,
    js2svg: {
        indent: 2, // string with spaces or number of spaces. 4 by default
        pretty: true, // boolean, false by default
    },
    plugins: [
        {
            name: 'preset-default',
        },
        {
            name: 'removeViewBox',
            active: false,
        },
        {
            name: 'addAttributesToSVGElement',
            params: {
                attributes: [{ xmlns: 'http://www.w3.org/2000/svg' }],
            },
        },
        'prefixIds',
        // it's necessary to remove all dimension tags to allow resizing
        'removeDimensions',
        'removeRasterImages',
        'removeScripts',
        'convertStyleToAttrs',
    ],
};

const optimizeSvgAssets = assetsDirname => {
    const assetsDir = path.join(__dirname, assetsDirname);
    const assetFileNames = fs.readdirSync(assetsDir);

    return assetFileNames
        .filter(fileName => fileName.endsWith('.svg'))
        .map(fileName => ({
            fileName,
            content: fs.readFileSync(path.resolve(assetsDir, fileName)).toString(),
        }))
        .map(({ fileName, content }) => ({
            fileName,
            content: optimize(content, svgoConfig).data,
        }));
};

const listRasterAssets = assetsDirname => {
    const assetsDir = path.join(__dirname, assetsDirname);

    return fs
        .readdirSync(assetsDir)
        .filter(fileName => fileName.endsWith('.webp'))
        .map(fileName => ({ fileName }));
};

const getOptimizedAssetTypes = assetTypesArray =>
    assetTypesArray.map(config => ({
        ...config,
        assets: config.raster
            ? listRasterAssets(config.dirname)
            : optimizeSvgAssets(config.dirname),
    }));

const generateIconsFileContent = assetTypesArray => {
    const imports = new Set();
    const assetGroups = new Map();

    assetTypesArray.forEach(({ name, assets, dirname, typeName, family }) => {
        const moduleName = family ? `${family}${name[0].toUpperCase()}${name.slice(1)}` : undefined;
        if (moduleName) {
            imports.add(`import { ${moduleName} } from '@trezor/network-${family}-assets';`);
        }

        const group = assetGroups.get(name) ?? { typeName, entries: [] };
        assets.forEach(({ fileName }) => {
            const symbol = fileName.replace(/\.(svg|webp)$/, '');
            const source = moduleName
                ? `${moduleName}.${symbol}.getIcon()`
                : `require('../${dirname}/${fileName}')`;
            group.entries.push({ symbol, source });
        });
        assetGroups.set(name, group);
    });

    const mappedAssetTypes = [...assetGroups].map(
        ([name, { typeName, entries }]) => `
            export const ${name} = {
                ${entries
                    .toSorted((a, b) => a.symbol.localeCompare(b.symbol))
                    .map(({ symbol, source }) => `${symbol}: ${source}`)
                    .join(',')}
            } as const;
            export type ${typeName} = keyof typeof ${name};
        `,
    );

    return `
    ${generatedFileHeader}
    // If you want to add of modify icons please read README.md to find out how to do it

    ${[...imports].join('\n')}
    ${mappedAssetTypes.join('')}
    `;
};

const writeOptimizedAssets = assetTypesArray => {
    assetTypesArray.forEach(({ assets, dirname, raster }) => {
        if (raster) {
            return;
        }
        assets.forEach(({ fileName, content }) =>
            fs.writeFileSync(path.resolve(dirname, fileName), content),
        );
    });
};

const generateFileForAssetTypes = async (assetTypesArray, outputFilePath) => {
    const assetTypes = getOptimizedAssetTypes(assetTypesArray);

    const iconsFileContent = generateIconsFileContent(assetTypes);

    const prettierConfigPath = await prettier.resolveConfigFile();
    const prettierConfig = {
        ...(await prettier.resolveConfig(prettierConfigPath)),
        parser: 'babel-ts',
    };

    const formattedIconTypesFileContent = await prettier.format(iconsFileContent, prettierConfig);

    fs.writeFileSync(path.resolve(outputFilePath), formattedIconTypesFileContent);

    for (const { name, assets, dirname, family } of assetTypes) {
        if (!family) continue;

        const moduleName = `${family}${name[0].toUpperCase()}${name.slice(1)}`;
        const moduleSource = `
            ${generatedFileHeader}
            // Keep SVG loading lazy so Node tools can resolve paths without loading the files.
            // Webpack can wrap SVG URLs in a default export; Metro returns the asset directly.
            export const ${moduleName} = {
                ${assets
                    .map(({ fileName }) => {
                        const symbol = fileName.replace(/\.svg$/, '');
                        const assetPath = `../assets/${name}/${fileName}`;

                        return `${symbol}: {
                            getIcon: () => {
                                const icon = require('${assetPath}');

                                return icon.default ?? icon;
                            },
                            getIconPath: () => require.resolve('${assetPath}'),
                        }`;
                    })
                    .join(',')}
            } as const;
        `;
        const modulePath = path.resolve(__dirname, dirname, '../../src', `${name}.ts`);

        fs.writeFileSync(modulePath, await prettier.format(moduleSource, prettierConfig));
    }

    writeOptimizedAssets(assetTypes);
};

(async () => {
    console.log('Generating icons TS file...');
    await generateFileForAssetTypes(assetTypesConfig, iconsFilePath);
    console.log(chalk.green('Icons TS file generated successfully'));
    console.log('Generating crypto icons TS file...');
    await generateFileForAssetTypes(cryptoAssetsTypesConfig, cryptoIconsPath);
    console.log(chalk.green('Crypto icons TS file generated successfully'));
    console.log('Generating network icons TS file...');
    await generateFileForAssetTypes(networkAssetsTypesConfig, networkIconsPath);
    console.log(chalk.green('Network icons TS file generated successfully'));
    console.log('Generating payment method logos TS file...');
    await generateFileForAssetTypes(paymentMethodLogosAssetsTypesConfig, paymentMethodLogosPath);
    console.log(chalk.green('Payment method logos TS file generated successfully'));
})();
