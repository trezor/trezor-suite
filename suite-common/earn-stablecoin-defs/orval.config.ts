import { type ClientGeneratorsBuilder, defineConfig } from 'orval';
import { resolve } from 'path';

import { addNamedSchemaFacades } from './orval/addNamedSchemaFacades';
import { EarnYieldWorkerBaseUrl } from './src';

const ESLINT_DISABLE_HEADER =
    '/* eslint-disable no-useless-escape, @typescript-eslint/no-empty-object-type */';

const API_DIR = resolve(import.meta.dirname, './src/api');
// TODO: take it from `suite-common/earn-stablecoin-api/src/context` once the @suite-common/earn-stablecoin-defs gets merged with @suite-common/earn-stablecoin-api.
const YIELD_BASE_URL: EarnYieldWorkerBaseUrl = 'http://localhost:3001/yield';

// eslint-disable-next-line import/no-default-export
export default defineConfig({
    earnYield: {
        input: {
            target: `${YIELD_BASE_URL}/openapi`,
        },
        output: {
            mode: 'single',
            target: resolve(API_DIR, 'index.ts'),
            clean: true,
            tsconfig: './tsconfig.json',
            packageJson: './package.json',
            fileExtension: '.ts',
            client: clients => {
                const zodClient = clients.zod;

                return {
                    ...zodClient,
                    client: async (verbOptions, options, output) => {
                        const result = await zodClient.client(verbOptions, options, output);

                        return {
                            ...result,
                            implementation: addNamedSchemaFacades(result.implementation),
                        };
                    },
                } satisfies ClientGeneratorsBuilder;
            },
            override: {
                // Prepend the ESLint directive (followed by orval's standard "do not edit"
                // notice) to the top of the generated file. A `header` returning a string is
                // written verbatim at the start of the output; the per-operation `transformer`
                // hook never sees the file header, so it can't be used for this.
                header: info =>
                    [
                        ESLINT_DISABLE_HEADER,
                        '',
                        '/**',
                        ' * Generated by orval 🍺',
                        ' * Do not edit manually.',
                        ` * ${info.title}`,
                        ` * OpenAPI spec version: ${info.version}`,
                        ' */',
                    ].join('\n') + '\n',
                zod: {
                    generateReusableSchemas: true,
                    generateMeta: true,
                    coerce: {
                        query: true,
                    },
                },
            },
        },
    },
});
