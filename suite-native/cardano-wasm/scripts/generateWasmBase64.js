/**
 * Reads the cardano-serialization-lib WASM binary from node_modules
 * and writes it as a base64-encoded JS module.
 *
 * Run: yarn workspace @suite-native/cardano-wasm generate-wasm
 *
 * The output file (src/generated/cardanoWasmBase64.js) is gitignored.
 * It must be regenerated after changing the CSL package version.
 */

const fs = require('fs');
const path = require('path');

const WASM_PATH = path.resolve(
    __dirname,
    '../../../node_modules/@emurgo/cardano-serialization-lib-browser/cardano_serialization_lib_bg.wasm',
);
const OUTPUT_PATH = path.resolve(__dirname, '../src/generated/cardanoWasmBase64.js');

if (!fs.existsSync(WASM_PATH)) {
    console.error(`WASM file not found at ${WASM_PATH}`);
    console.error('Run "yarn install" first.');
    process.exit(1);
}

const wasmBytes = fs.readFileSync(WASM_PATH);
const base64 = wasmBytes.toString('base64');

const output = `// Auto-generated by scripts/generateWasmBase64.js — do not edit.\n// Source: @emurgo/cardano-serialization-lib-browser v13.2.0\n// Size: ${wasmBytes.length} bytes (${(base64.length / 1024 / 1024).toFixed(1)} MB base64)\nmodule.exports = "${base64}";\n`;

fs.mkdirSync(path.dirname(OUTPUT_PATH), { recursive: true });
fs.writeFileSync(OUTPUT_PATH, output);

console.log(`Generated ${OUTPUT_PATH} (${(base64.length / 1024 / 1024).toFixed(1)} MB)`);
