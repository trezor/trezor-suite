import path from 'path';
import type { Options } from 'prettier';

import type { WriteFileDep } from '@trezor/type-utils';

import { generateNetworkAssetsSource } from './generateNetworkAssetsSource';
import type { RegenerateNetworkIcons } from '../src/NetworkAssetsModuleApi';

export type RegenerateNetworkIconsDeps = WriteFileDep & {
    repositoryRoot: string;
    readDirectory: (directory: string) => Promise<string[]>;
    resolvePrettierConfig: (filePath: string) => Promise<Options | null>;
    formatTypescript: (source: string, config: Options) => Promise<string>;
};

type GenerateIconLoadersParams = {
    family: string;
    name: string;
    symbols: readonly string[];
};

const generateIconLoaders = ({ family, name, symbols }: GenerateIconLoadersParams): string => `
    // !!! IMPORTANT: This file is autogenerated !!!
    // Keep SVG loading lazy so Node tools can resolve paths without loading the files.
    // Webpack can wrap SVG URLs in a default export; Metro returns the asset directly.
    export const ${family}${name[0].toUpperCase()}${name.slice(1)} = {
        ${symbols
            .map(
                symbol => `${symbol}: {
                    getIcon: () => {
                        const icon = require('../assets/${name}/${symbol}.svg');

                        return icon.default ?? icon;
                    },
                    getIconPath: () => require.resolve('../assets/${name}/${symbol}.svg'),
                }`,
            )
            .join(',')}
    } as const;
`;

/** Owns regeneration for the standard network asset package layout. */
export const createRegenerateNetworkIcons = (
    deps: RegenerateNetworkIconsDeps,
): RegenerateNetworkIcons => {
    const writeTypescript = async (filePath: string, source: string): Promise<void> => {
        const config = await deps.resolvePrettierConfig(filePath);
        const formattedSource = await deps.formatTypescript(source, {
            ...config,
            parser: 'babel-ts',
        });
        await deps.writeFile(filePath, Buffer.from(formattedSource));
    };

    return async ({ family, supportedNetworks, icons }) => {
        const packageDirectory = path.join(
            deps.repositoryRoot,
            'networks',
            family,
            `network-${family}-assets`,
        );
        const readSymbols = async (name: string): Promise<string[]> => {
            const fileNames = await deps.readDirectory(path.join(packageDirectory, 'assets', name));

            return fileNames
                .filter(fileName => fileName.endsWith('.svg'))
                .toSorted()
                .map(fileName => fileName.slice(0, -4));
        };
        const cryptoIconSymbols = await readSymbols('cryptoIcons');
        const networkIconSymbols = await readSymbols('networkIcons');
        // Crypto-only assets such as GNT belong in the loaders without a network facade entry.
        const symbols = cryptoIconSymbols
            .filter(
                symbol =>
                    symbol in icons ||
                    supportedNetworks.includes(symbol) ||
                    networkIconSymbols.includes(symbol),
            )
            .map(symbol => {
                const network = icons[symbol]
                    ? path.basename(icons[symbol].getIconPaths().network, '.svg')
                    : symbol;

                if (!networkIconSymbols.includes(network)) {
                    throw new Error(`Missing network icon '${network}' for '${symbol}' in ${family}.`);
                }

                return { symbol, coin: symbol, network };
            });

        for (const [name, iconSymbols] of [
            ['cryptoIcons', cryptoIconSymbols],
            ['networkIcons', networkIconSymbols],
        ] as const) {
            await writeTypescript(
                path.join(packageDirectory, 'src', `${name}.ts`),
                generateIconLoaders({ family, name, symbols: iconSymbols }),
            );
        }
        await writeTypescript(
            path.join(packageDirectory, 'src', `${family}Assets.ts`),
            generateNetworkAssetsSource({
                family,
                symbols,
                extraSymbols: symbols
                    .map(({ symbol }) => symbol)
                    .filter(symbol => !supportedNetworks.includes(symbol)),
            }),
        );
    };
};
