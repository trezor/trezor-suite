#!/usr/bin/env tsx

import { type AnyDesc, DescEnum, DescExtension, DescMessage, ScalarType } from '@bufbuild/protobuf';
import { Schema, createEcmaScriptPlugin, runNodeJs } from '@bufbuild/protoplugin';

import { generateTypeBox } from '@trezor/schema-utils/src/codegen';

import {
    DEFINITION_PATCH,
    ENUM_KEYS,
    FIELD_TYPES,
    RULE_PATCH,
    SKIP,
    TYPE_PATCH,
    UINT_TYPE,
    readPatch,
} from './protobuf-patches/index';

const PROTOC_PLUGIN_NAME = '@trezor/protobuf/protoc-gen-plugin';
const PROTOC_PLUGIN_VERSION = '1.0.0';
const PROTO_LABEL_REQUIRED = 2; // FieldDescriptorProto_Label.REQUIRED from @bufbuild/protobuf/wkt

type TypeItem = {
    type: 'enum' | 'message';
    name: string;
    value: string;
};

type TypeFileBuild = {
    lines: string[];
    body: string[];
    externalTypes: string[];
};

type PluginOptions = {
    // list of .proto files to generate *_types.ts file which contains only type definitions (without schema generation)
    // usage: --types=messages-management+messages-bitcoin+...
    types: string[];
};

const parseOptions = (rawOptions: { key: string; value: string }[]): PluginOptions => ({
    types: rawOptions
        .map(({ key, value }) => {
            if (key !== 'types') throw new Error(`Unknown option: ${key}`);

            return value.split('+').filter(Boolean);
        })
        .flat(),
});

const disclaimer = (file?: Schema<PluginOptions>['files'][number]) =>
    [
        `// @generated by ${PROTOC_PLUGIN_NAME} ${PROTOC_PLUGIN_VERSION}`,
        file && `// source: ${file.name}.proto`,
        '// DO NOT EDIT',
    ]
        .filter(Boolean)
        .join('\n');

const scalarToProtoName = (scalar: ScalarType) => {
    switch (scalar) {
        case ScalarType.UINT32:
            return 'uint32';
        case ScalarType.UINT64:
            return 'uint64';
        case ScalarType.INT32:
            return 'int32';
        case ScalarType.INT64:
            return 'int64';
        case ScalarType.SINT32:
            return 'sint32';
        case ScalarType.SINT64:
            return 'sint64';
        case ScalarType.FIXED32:
            return 'fixed32';
        case ScalarType.FIXED64:
            return 'fixed64';
        case ScalarType.SFIXED32:
            return 'sfixed32';
        case ScalarType.SFIXED64:
            return 'sfixed64';
        case ScalarType.FLOAT:
            return 'float';
        case ScalarType.DOUBLE:
            return 'double';
        case ScalarType.BOOL:
            return 'bool';
        case ScalarType.STRING:
            return 'string';
        case ScalarType.BYTES:
            return 'bytes';
        default:
            throw new Error(`Unhandled ScalarType: ${scalar}`);
    }
};

const getFieldBaseType = (field: DescMessage['fields'][number]): string => {
    switch (field.fieldKind) {
        case 'scalar':
            return scalarToProtoName(field.scalar);
        case 'enum':
            return field.enum.name;
        case 'message':
            return field.message.name;
        case 'list':
            switch (field.listKind) {
                case 'scalar':
                    return scalarToProtoName(field.scalar);
                case 'enum':
                    return field.enum.name;
                case 'message':
                    return field.message.name;
                default:
                    throw new Error(
                        `Unhandled listKind: ${(field as { listKind: string }).listKind}`,
                    );
            }
        case 'map':
            return 'Record<string, unknown>';
        default:
            throw new Error(`Unhandled fieldKind: ${(field as { fieldKind: string }).fieldKind}`);
    }
};

const generateEnumItem = (desc: DescEnum): TypeItem => {
    const isKey = ENUM_KEYS.includes(desc.name);
    const enumName = isKey ? `Enum_${desc.name}` : desc.name;
    const lines = [`export enum ${enumName} {`];
    for (const value of desc.values) {
        lines.push(`    ${value.name} = ${value.number},`);
    }
    lines.push('}', '');
    if (isKey) {
        lines.push(`export type ${desc.name} = keyof typeof ${enumName};`, '');
    }

    return { type: 'enum', name: desc.name, value: lines.join('\n') };
};

const generateMessageItem = (desc: DescMessage): TypeItem => {
    const messageName = desc.name as keyof typeof DEFINITION_PATCH;
    const lines: string[] = [];

    if (DEFINITION_PATCH[messageName]) {
        lines.push(DEFINITION_PATCH[messageName]());
    } else if (!desc.fields || desc.fields.length === 0) {
        lines.push(`export type ${messageName} = {};`, '');
    } else {
        lines.push(`export type ${messageName} = {`);
        for (const field of desc.fields) {
            const fieldName: string = field.name;
            const fieldKey = `${messageName}.${fieldName}` as keyof typeof RULE_PATCH;
            const isRepeated = field.fieldKind === 'list';
            const isRequired = !isRepeated && field.proto.label === PROTO_LABEL_REQUIRED;

            let rawRule: 'repeated' | 'required' | 'optional' = 'optional';
            if (isRepeated) {
                rawRule = 'repeated';
            } else if (isRequired) {
                rawRule = 'required';
            }
            const patchedRule = RULE_PATCH[fieldKey] || rawRule;
            const separator =
                patchedRule === 'required' || patchedRule === 'repeated' ? ': ' : '?: ';

            const baseTypeProtoName = getFieldBaseType(field);
            let type: string =
                TYPE_PATCH[fieldKey as keyof typeof TYPE_PATCH] ||
                FIELD_TYPES[baseTypeProtoName as keyof typeof FIELD_TYPES] ||
                baseTypeProtoName;

            if (
                !TYPE_PATCH[fieldKey as keyof typeof TYPE_PATCH] &&
                ['amount', 'fee'].includes(fieldName)
            ) {
                type = UINT_TYPE;
            }
            if (isRepeated) {
                type = type.split('|').length > 1 ? `Array<${type}>` : `${type}[]`;
            }

            lines.push(`    ${fieldName}${separator}${type};`);
        }
        lines.push('};', '');
    }

    return { type: 'message', name: messageName, value: lines.join('\n') };
};

const sortTypeItems = (types: TypeItem[]) => {
    if (types.length < 2) return;

    // Base sort: enums first, then alphabetical
    types.sort((a, b) => {
        if (a.type !== b.type) return a.type === 'enum' ? -1 : 1;

        return a.name.localeCompare(b.name);
    });

    // Build dependency graph by extracting identifiers from each item's value
    const nameSet = new Set(types.map(item => item.name));
    const itemByName = new Map(types.map(item => [item.name, item]));
    const depsByName = new Map<string, Set<string>>();
    for (const item of types) {
        const deps = new Set<string>();
        const identifiers = item.value.match(/\b[A-Za-z_][A-Za-z0-9_]*\b/g) ?? [];
        for (const id of identifiers) {
            if (id !== item.name && nameSet.has(id)) {
                deps.add(id);
            }
        }
        depsByName.set(item.name, deps);
    }

    // Topological sort preserving base order for independent items
    const result: TypeItem[] = [];
    const visited = new Set<string>();
    const visiting = new Set<string>();

    const visit = (name: string) => {
        if (visited.has(name)) return;
        if (visiting.has(name)) {
            console.warn(`Cyclic type dependency detected while sorting schema types: ${name}`);

            return;
        }

        visiting.add(name);
        for (const dep of depsByName.get(name) ?? []) {
            visit(dep);
        }
        visiting.delete(name);
        visited.add(name);

        const item = itemByName.get(name);
        if (item) {
            result.push(item);
        }
    };

    for (const item of types) {
        visit(item.name);
    }

    types.length = 0;
    types.push(...result);
};

type SchemaContext = {
    files: string[];
    owners: Map<string, string>;
    messageType: {
        wireMessages: Set<string>;
        wireIn: Set<string>;
        wireOut: Set<string>;
    };
};

// Step 1: collect all messages, enums and extensions from the schema.
// find out which messages are wire messages (have wire_in or wire_out option or are referenced by other message with wire_type option)
// find out which messages are wire_in and which are wire_out
const getSchemaContext = (schema: Schema<PluginOptions>): SchemaContext => {
    const owners = new Map<string, string>();
    const wireIn = new Set<string>();
    const wireOut = new Set<string>();
    const wireMessages = new Set<string>();
    const files: string[] = [];

    const enums = new Map<string, DescEnum>();
    const extensions = new Map<string, DescExtension>();
    const messages = new Map<string, DescMessage>();

    for (const file of schema.files) {
        files.push(file.name);
        for (const desc of schema.typesInFile(file)) {
            if (desc.kind === 'enum') {
                enums.set(desc.name, desc);
                owners.set(desc.name, file.name);
                if (ENUM_KEYS.includes(desc.name)) {
                    owners.set(`Enum_${desc.name}`, file.name);
                }
            } else if (desc.kind === 'extension') {
                extensions.set(desc.name, desc);
            } else if (desc.kind === 'message') {
                messages.set(desc.name, desc);
                owners.set(desc.name, file.name);
            }
        }
    }

    const findMessageTypeByName = (enumName: string, messageName: string) =>
        enums.get(enumName)?.values.find(v => v && v.name === enumName + '_' + messageName);

    const findMessageTypeById = (enumName: string, messageValue: number) =>
        enums.get(enumName)?.values.find(v => v && v.number === messageValue);

    const findMessageType = (message: string | number) => {
        for (const enumName of ['MessageType', 'ThpMessageType']) {
            const messageType =
                typeof message === 'string'
                    ? findMessageTypeByName(enumName, message)
                    : findMessageTypeById(enumName, message);
            if (messageType) {
                return messageType;
            }
        }

        return undefined;
    };

    const findOptions = (proto: AnyDesc['proto'] | undefined, optionNames: string[]) => {
        const options = proto?.options?.['$unknown'];
        if (!options || !Array.isArray(options)) return [];

        return optionNames.map(optionName => {
            const extensionId = extensions.get(optionName)?.number;

            return extensionId ? options.find(o => o.no === extensionId) : undefined;
        });
    };

    for (const [name, desc] of messages) {
        if (SKIP.includes(name)) {
            continue;
        }

        const isMessageType = findMessageType(name);
        if (isMessageType) {
            const [isWireIn, isWireOut] = findOptions(isMessageType.proto, ['wire_in', 'wire_out']);
            if (isWireIn) {
                wireIn.add(name);
            }
            if (isWireOut) {
                wireOut.add(name);
            }
            wireMessages.add(name);

            continue;
        }

        const [wireTypeOption] = findOptions(desc.proto, ['wire_type']);
        if (wireTypeOption) {
            if (!wireTypeOption.data || wireTypeOption.data.length === 0) {
                throw new Error(`wire_type option for message '${name}' has no data`);
            }
            const wiredMessageType = findMessageType(wireTypeOption.data[0]);
            if (!wiredMessageType) {
                throw new Error(
                    `wire_type ${wireTypeOption.data[0]} for message '${name}' not found in MessageType/ThpMessageType`,
                );
            }
            const [isWireIn, isWireOut] = findOptions(wiredMessageType.proto, [
                'wire_in',
                'wire_out',
            ]);
            if (isWireIn) {
                wireIn.add(name);
            }
            if (isWireOut) {
                wireOut.add(name);
            }
            wireMessages.add(name);
        }
    }

    return {
        files,
        owners,
        messageType: { wireIn, wireOut, wireMessages },
    };
};

const extractExternalTypeRefs = (
    source: string,
    currentFileName: string,
    owners: Map<string, string>,
) => {
    const refs = new Set<string>();
    // Strip string literals and comments to avoid false matches
    const stripped = source
        .replace(/\/\/.*$/gm, '')
        .replace(/\/\*[\s\S]*?\*\//g, '')
        .replace(/'[^']*'/g, '')
        .replace(/"[^"]*"/g, '');
    const matches = stripped.match(/\b[A-Za-z_][A-Za-z0-9_]*\b/g) ?? [];
    for (const candidate of matches) {
        const owner = owners.get(candidate);
        if (owner && owner !== currentFileName) {
            refs.add(candidate);
        }
    }

    return refs;
};

const buildImportLines = (
    externalTypes: string[],
    fileName: string,
    owners: Map<string, string>,
    importStyle: 'type' | 'value',
): string[] => {
    const importsByOwner = new Map<string, string[]>();
    for (const externalType of externalTypes) {
        const owner = owners.get(externalType);
        if (!owner || owner === fileName) continue;
        const list = importsByOwner.get(owner) ?? [];
        list.push(externalType);
        importsByOwner.set(owner, list);
    }

    const prefix = importStyle === 'type' ? 'import type' : 'import';

    return [...importsByOwner.entries()]
        .sort(([a], [b]) => a.localeCompare(b))
        .map(([owner, names]) => {
            const unique = [...new Set(names)].sort((a, b) => a.localeCompare(b));
            const suffix = importStyle === 'type' ? '_types' : '';

            return `${prefix} { ${unique.join(', ')} } from './${owner}${suffix}';`;
        });
};

// Step 2: generate typescript definitions for messages and enums.
// apply patches for specific cases
// collect imports for referenced items
const buildTypeFile = (
    schema: Schema<PluginOptions>,
    file: Schema<PluginOptions>['files'][number],
    { owners }: SchemaContext,
): TypeFileBuild => {
    const typeItems: TypeItem[] = [];
    for (const desc of schema.typesInFile(file)) {
        if (SKIP.includes(desc.name)) {
            continue;
        }
        if (desc.kind === 'enum') {
            typeItems.push(generateEnumItem(desc));
        } else if (desc.kind === 'message') {
            typeItems.push(generateMessageItem(desc));
        }
    }

    if (file.name === 'messages-management') {
        typeItems.push({
            type: 'enum',
            name: 'DeviceModelInternal',
            value: readPatch('../../../device-utils/src/deviceModelInternal.ts'),
        });
    }

    sortTypeItems(typeItems);

    const externalRefs = new Set<string>();
    for (const item of typeItems) {
        const refs = extractExternalTypeRefs(item.value, file.name, owners);
        for (const ref of refs) externalRefs.add(ref);
    }

    const body: string[] = [];
    for (const item of typeItems) {
        body.push(item.value);
    }

    const externalTypes = [...externalRefs].sort((a, b) => a.localeCompare(b));
    const importLines = buildImportLines(externalTypes, file.name, owners, 'type');

    const lines: string[] = [disclaimer(file), ''];
    if (importLines.length > 0) {
        lines.push(...importLines, '');
    }
    if (body.length > 0) {
        lines.push(...body);
    } else {
        lines.push('export {};');
    }

    return {
        lines,
        body,
        externalTypes,
    };
};

const generateTypes = (schema: Schema<PluginOptions>, schemaContext: SchemaContext) => {
    const typeFileNames = new Set(schema.options.types);
    for (const file of schema.files) {
        if (!typeFileNames.has(file.name)) {
            continue;
        }
        const f = schema.generateFile(file.name + '_types.ts');
        const result = buildTypeFile(schema, file, schemaContext);
        f.print(result.lines.join('\n'));
    }
};

// Step 4: generate index.ts file with exports of all messages and enums
// create MessageType schema with all wire messages
// create WireInMessage and WireOutMessage union types based on MessageType enum values
const generateIndexFile = (
    schema: Schema<PluginOptions>,
    { files, owners, messageType }: SchemaContext,
) => {
    const f = schema.generateFile('index.ts');
    f.print(disclaimer());

    const lines: string[] = [];

    for (const messageName of messageType.wireMessages) {
        const owner = owners.get(messageName);
        if (owner) {
            lines.push(`import { ${messageName} } from './${owner}';`);
        }
    }

    lines.push("import { type Static, Type } from '@trezor/schema-utils';");
    lines.push('');

    for (const file of files) {
        lines.push(`export * from './${file}';`);
    }
    lines.push('');

    lines.push('export type MessageType = Static<typeof MessageType>;');
    lines.push('export const MessageType = Type.Object({');
    for (const messageName of messageType.wireMessages) {
        lines.push(messageName + ': ' + messageName + ',');
    }
    lines.push("}, { $id: 'MessageType' });");
    lines.push('');

    const wireInUnion =
        messageType.wireIn.size > 0
            ? Array.from(messageType.wireIn)
                  .map(n => `'${n}'`)
                  .join(' | ')
            : 'never';
    lines.push(`export type WireInMessage = ${wireInUnion};`);

    lines.push('');

    const wireOutUnion =
        messageType.wireOut.size > 0
            ? Array.from(messageType.wireOut)
                  .map(n => `'${n}'`)
                  .join(' | ')
            : 'never';
    lines.push(`export type WireOutMessage = ${wireOutUnion};`);

    lines.push(readPatch('MessageType.ts'));

    f.print(lines.join('\n'));
};

// generate *.ts files for corresponding _pb.js files, create types and message schema for each _pb.js file
const generateTs = (schema: Schema<PluginOptions>) => {
    const schemaContext = getSchemaContext(schema);

    for (const file of schema.files) {
        const f = schema.generateFile(file.name + '.ts');
        f.print(disclaimer(file));

        const result = buildTypeFile(schema, file, schemaContext);
        const source = result.body.join('\n');

        if (!source.trim()) {
            f.print('export {};');
            continue;
        }
        // Step 3: generate schema definitions from typescript definitions
        // collect imports for referenced items
        // apply manual patches for specific cases
        const schemaContent = generateTypeBox(source, {
            appendHelpersForMessageType: false,
        });

        const schemaImports = buildImportLines(
            result.externalTypes,
            file.name,
            schemaContext.owners,
            'value',
        );

        const body =
            schemaImports.length > 0
                ? [...schemaImports, '', schemaContent].join('\n')
                : schemaContent;

        f.print(body);
    }

    generateTypes(schema, schemaContext);

    generateIndexFile(schema, schemaContext);
};

const generateJs = () => {
    // *._pb.js files are generated by the protoc-gen-es plugin. see: buf.gen.yaml
};

const generateDts = (schema: Schema<PluginOptions>) => {
    // generate *.d.ts files for corresponding _pb.js files, declare DescFile definitions for each _pb.js file
    for (const file of schema.files) {
        const f = schema.generateFile(file.name + '_pb.d.ts');
        f.print(disclaimer(file));
        f.print("import type { DescFile } from '@bufbuild/protobuf';");
        f.print();

        f.print(`export declare const file_${file.name.replace(/-/g, '_')}: DescFile;`);
    }
};

export const protocGenTrezor = createEcmaScriptPlugin({
    name: PROTOC_PLUGIN_NAME,
    version: PROTOC_PLUGIN_VERSION,
    parseOptions,
    generateTs,
    generateJs,
    generateDts,
});

runNodeJs(protocGenTrezor);
