import { mkdir, readdir, rm, writeFile } from 'node:fs/promises';
import { extname } from 'node:path';

import { getIconExportName } from './getIconExportName.mjs';

const generatedIconsDirectory = new URL('./src/generated/icons/', import.meta.url);
const iconTypesDirectory = new URL('./src/types/', import.meta.url);
const iconTypesIndex = new URL('./src/index.ts', import.meta.url);

const generatedIconFileNames = (await readdir(generatedIconsDirectory))
    .filter(fileName => extname(fileName) === '.tsx')
    .sort();
const iconExportNamesByGroup = new Map();

for (const fileName of generatedIconFileNames) {
    const groupName = getIconExportName(fileName).at(0);
    const groupedFileNames = iconExportNamesByGroup.get(groupName);

    if (groupedFileNames) {
        groupedFileNames.push(fileName);
    } else {
        iconExportNamesByGroup.set(groupName, [fileName]);
    }
}

const generatedFileHeader = '// This file is generated by generateIconTypes.mjs.';

await rm(iconTypesDirectory, { recursive: true, force: true });
await mkdir(iconTypesDirectory);

await Promise.all(
    [...iconExportNamesByGroup].map(([groupName, fileNames]) => {
        const iconTypeExports = fileNames.map(
            fileName => `export declare const ${getIconExportName(fileName)}: IconComponent;`,
        );
        const iconTypes = [
            generatedFileHeader,
            '',
            "import type { JSX, SVGProps } from 'react';",
            '',
            'type IconComponent = (props: SVGProps<SVGSVGElement>) => JSX.Element;',
            '',
            ...iconTypeExports,
            '',
        ].join('\n');

        return writeFile(new URL(`${groupName}.ts`, iconTypesDirectory), iconTypes);
    }),
);

const iconTypesIndexContent = [
    generatedFileHeader,
    '',
    ...[...iconExportNamesByGroup.keys()].map(groupName => `export * from './types/${groupName}';`),
    '',
].join('\n');

await writeFile(iconTypesIndex, iconTypesIndexContent);
